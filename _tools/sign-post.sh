#!/usr/bin/env bash
# Clearsign blog posts with the Deep Woods Security PGP key, and build the
# signature index that the post layout renders at the bottom of each post.
set -euo pipefail
cd "$(dirname "$0")/.."
FPR="9C9A2284DFBD39E78AF65EB845C5EDBB4236E1E5"
SIGDIR="sig"
POSTS="_posts"
mkdir -p "$SIGDIR" _data

sign_one() {
  local f="$1" base; base="$(basename "$f")"
  gpg --local-user "$FPR" --armor --yes --digest-algo SHA512 \
      --output "$SIGDIR/$base.asc" --clearsign "$f"
  echo "signed   $base"
}

check_one() {
  local f="$1" base; base="$(basename "$f")"
  if [[ ! -f "$SIGDIR/$base.asc" ]]; then echo "MISSING  $base"; return; fi
  if gpg --verify "$SIGDIR/$base.asc" >/dev/null 2>&1; then echo "OK       $base"; else echo "BAD      $base"; fi
}

regen_index() {
  local out="_data/signatures.yml" f base asc
  echo "# generated by _tools/sign-post.sh -- do not edit by hand" > "$out"
  for f in "$POSTS"/*.md; do
    base="$(basename "$f")"; asc="$SIGDIR/$base.asc"
    [[ -f "$asc" ]] || continue
    echo "$base: |" >> "$out"
    sed -n '/-----BEGIN PGP SIGNATURE-----/,/-----END PGP SIGNATURE-----/p' "$asc" | sed 's/^/  /' >> "$out"
  done
  echo "wrote    $out"
}

case "${1:-}" in
  --export-key) gpg --armor --export "$FPR" > pgp.asc; echo "wrote pgp.asc" ;;
  --all)        for f in "$POSTS"/*.md; do sign_one "$f"; done; regen_index ;;
  --check)      for f in "$POSTS"/*.md; do check_one "$f"; done ;;
  --index)      regen_index ;;
  ""|-h|--help) echo "usage: _tools/sign-post.sh [--all | --check | --export-key | --index | <post.md>]" ;;
  *)            sign_one "$1"; regen_index ;;
esac
